/// Fast disambiguation window for a chord leader that also has a single-key
/// mapping.  This is short enough to feel immediate on a normal key tap.
const CHORD_FAST_MS: u64 = 45;
/// Longer window when the leader has no single-key/function action: a miss
/// simply does nothing, so we can wait for a less-perfect chord rollover.
const CHORD_SLOW_MS: u64 = 120;

/// 事件等待的"快档"毫秒数:映射已开启且通道在线时的轮询间隔。
/// 4ms 足够让瞄准的静止归中与鼠标捕获状态保持跟手,
/// 同时把引擎线程的空转次数控制在 250 次/秒以内。
///
/// 注意:此档位(以及所有 `scheduled` 计划动作的等到期)依赖进程已提升定时器精度
/// ——见 `timer::raise()`(main 启动时调用)。否则 Windows 会把 `recv_timeout`
/// 的 4ms 量化成 ~10.2ms(实测),计划动作派遣误差 ±6~10ms。
const IDLE_FAST_MS: u64 = 4;

/// 事件等待的"慢档"毫秒数:没连接设备 / 未开启映射时的轮询间隔。
/// 此时循环体不做任何事(没有事件就没有触点要维护),继续按快档空转
/// 等于白烧 CPU 与锁 —— 设备没插着的时候尤其明显。
/// 事件到达会立即唤醒等待,所以这个退避不影响任何响应延迟。
const IDLE_SLOW_MS: u64 = 16;

/// Ctrl / Alt 的 evdev 键码,用于识别"Ctrl+Alt 交还鼠标"这一组合
const KEY_LEFTCTRL: u16 = 29;
const KEY_RIGHTCTRL: u16 = 97;
const KEY_LEFTALT: u16 = 56;
const KEY_RIGHTALT: u16 = 100;

fn is_ctrl(code: u16) -> bool {
    code == KEY_LEFTCTRL || code == KEY_RIGHTCTRL
}

fn is_alt(code: u16) -> bool {
    code == KEY_LEFTALT || code == KEY_RIGHTALT
}

/// Ctrl+Alt 组合的触发判定:两者都按住时,按下的那一方触发一次切换。
/// 这样一次组合只会切换一次,按住不放也不会连发。
fn ctrl_alt_chord(code: u16, pressed: bool, ctrl_down: bool, alt_down: bool) -> bool {
    pressed && ctrl_down && alt_down && (is_ctrl(code) || is_alt(code))
}

/// 引擎内部使用的按键事件:与 capture::CaptureEvent::Button 同构,
/// 保留 code/pressed 字段名以便下方既有逻辑直接复用。
#[derive(Clone, Copy)]
struct CaptureKey {
    code: u16,
    pressed: bool,
}

#[derive(Clone, Copy)]
enum EngineInput {
    Button(CaptureKey),
    Motion { dx: f32, dy: f32 },
    Combo { index: usize, pressed: bool },
}

struct ChordLeader {
    events: Vec<CaptureKey>,
    seen: HashSet<u16>,
    candidates: Vec<usize>,
    deadline: Instant,
}

#[derive(Default)]
struct ComboGate {
    queue: VecDeque<EngineInput>,
    leader: Option<ChordLeader>,
    active: Option<usize>,
    suppressed: HashSet<u16>,
}

impl ComboGate {
    fn reset(&mut self) {
        self.queue.clear();
        self.leader = None;
        self.active = None;
        self.suppressed.clear();
    }

    fn poll(&mut self, profile: &Profile) -> Option<EngineInput> {
        if !profile.combos_enabled {
            self.active = None;
            self.suppressed.clear();
            self.flush_leader();
        }
        if let Some(leader) = &self.leader
            && Instant::now() >= leader.deadline
        {
            self.flush_leader();
        }
        let _ = profile;
        self.queue.pop_front()
    }

    fn next_wait(&self, fallback: Duration) -> Duration {
        self.leader
            .as_ref()
            .map(|leader| leader.deadline.saturating_duration_since(Instant::now()))
            .map(|wait| wait.min(fallback))
            .unwrap_or(fallback)
            .max(Duration::from_millis(1))
    }

    fn flush_leader(&mut self) {
        if let Some(leader) = self.leader.take() {
            for event in leader.events {
                self.queue.push_back(EngineInput::Button(event));
            }
        }
    }

    fn ingest_button(
        &mut self,
        event: CaptureKey,
        profile: &Profile,
        switch_keys: &[SwitchKey],
    ) -> Option<EngineInput> {
        // 功能键必须绕开组合键判定队列。
        // 否则功能键被 45/120ms 判定窗口延迟或吞掉。
        // 典型表现就是“按了 F8 也停不下映射”。
        // 这些键是全局控制，优先级高于普通组合键。
        if event.code == profile.toggle_key
            || event.code == profile.cursor_toggle_key
            || event.code == profile.aim.toggle_key
            || event.code == profile.aim.suspend_key
            || event.code == profile.aim.hold_key
            || switch_keys
                .iter()
                .any(|s| s.effective_keys().contains(&event.code))
        {
            return Some(EngineInput::Button(event));
        }
        if !profile.combos_enabled || profile.combos.is_empty() {
            return Some(EngineInput::Button(event));
        }

        if self.suppressed.contains(&event.code) {
            if !event.pressed {
                self.suppressed.remove(&event.code);
                if let Some(index) = self.active.take() {
                    return Some(EngineInput::Combo {
                        index,
                        pressed: false,
                    });
                }
            }
            return None;
        }

        if self.active.is_some() {
            return Some(EngineInput::Button(event));
        }

        if let Some(mut leader) = self.leader.take() {
            if event.pressed {
                if let Some(index) = leader_completes(&profile.combos, &leader, event.code) {
                    self.active = Some(index);
                    self.suppressed = profile.combos[index].keys.iter().copied().collect();
                    return Some(EngineInput::Combo {
                        index,
                        pressed: true,
                    });
                }
                if leader_still_possible(&profile.combos, &leader, event.code) {
                    leader.seen.insert(event.code);
                    leader.events.push(event);
                    self.leader = Some(leader);
                    return None;
                }
            }

            // The candidate no longer matches (or a member was released
            // before all keys were down).  Replay the leader's buffered
            // events in order, then process this event normally.  Return the
            // first buffered event now and queue the rest so ordering is
            // preserved exactly.
            let mut first = None;
            for buffered in leader.events {
                if first.is_none() {
                    first = Some(EngineInput::Button(buffered));
                } else {
                    self.queue.push_back(EngineInput::Button(buffered));
                }
            }
            self.queue.push_back(EngineInput::Button(event));
            return first;
        }

        if event.pressed {
            let candidates: Vec<usize> = profile
                .combos
                .iter()
                .enumerate()
                .filter(|(_, combo)| combo.keys.contains(&event.code))
                .map(|(index, _)| index)
                .collect();
            if !candidates.is_empty() {
                let fast = key_has_single_action(profile, event.code);
                let wait_ms = if fast { CHORD_FAST_MS } else { CHORD_SLOW_MS };
                let mut seen = HashSet::new();
                seen.insert(event.code);
                self.leader = Some(ChordLeader {
                    events: vec![event],
                    seen,
                    candidates,
                    deadline: Instant::now() + Duration::from_millis(wait_ms),
                });
                return None;
            }
        }
        Some(EngineInput::Button(event))
    }
}

fn leader_completes(combos: &[KeyCombo], leader: &ChordLeader, code: u16) -> Option<usize> {
    leader.candidates.iter().copied().find(|&index| {
        let keys = &combos[index].keys;
        keys.iter()
            .all(|key| *key == code || leader.seen.contains(key))
    })
}

fn leader_still_possible(combos: &[KeyCombo], leader: &ChordLeader, code: u16) -> bool {
    leader
        .candidates
        .iter()
        .any(|&index| combos[index].keys.iter().any(|key| *key == code))
}

fn key_has_single_action(profile: &Profile, code: u16) -> bool {
    profile.binds.iter().any(|bind| bind.key == code)
        || profile.toggle_key == code
        || profile.aim.toggle_key == code
        || profile.aim.suspend_key == code
        || profile.aim.hold_key == code
        || profile.wheels.iter().any(|wheel| wheel.owns_key(code))
}

fn resolve_switch_target(
    switch: &SwitchKey,
    active_scheme: usize,
    scheme_count: usize,
) -> Option<usize> {
    match switch.direction {
        SwitchDirection::Target => (switch.target < scheme_count).then_some(switch.target),
        SwitchDirection::Next => (scheme_count != 0).then_some((active_scheme + 1) % scheme_count),
        SwitchDirection::Prev => {
            if scheme_count == 0 {
                None
            } else {
                Some((active_scheme + scheme_count - 1) % scheme_count)
            }
        }
    }
}

/// 普通键位并发跟踪器:每个绑定索引独立记录"是否已按下",
/// 保证任意键的按下/抬起严格成对、只作用于自己的 pid,互不干扰。
///  - 同键未抬起时忽略重复按下(全局钩子自动重复/抖动),避免向 scrcpy
///    反复注入同一 pid 的 DOWN,把 server 的多点指针池搅乱;
///  - 没有按下记录的抬起一律忽略,绝不误抬其它键;
///  - 同时按下的键数不超过 MAX_CONCURRENT_KEYS(超出忽略新按下)。
#[derive(Default)]
struct Fingers {
    /// 绑定索引 -> 是否已按下
    down: Vec<bool>,
    /// 当前按下中的键数
    count: usize,
}

impl Fingers {
    /// 绑定列表长度变化时补长(只增不减,删除绑定产生的残留由 free_all 兜底)
    fn align(&mut self, n: usize) {
        if self.down.len() < n {
            self.down.resize(n, false);
        }
    }

    fn is_down(&self, idx: usize) -> bool {
        self.down.get(idx).copied().unwrap_or(false)
    }

    /// 登记一次按下;已按下、并发已达上限、或**加上轮盘/瞄准占用的触点后**
    /// 会超过设备端触点池上限([`DEVICE_MAX_POINTERS`])时返回 false
    /// (调用方据此不注入 DOWN)。
    ///
    /// `others` 是此刻被轮盘与瞄准子系统占用的触点数 —— 它们和普通绑定抢同一个
    /// 设备端指针池,必须一起算,否则"按住好几个键 + 摇杆一直推着"时,
    /// 超出的那次按下会被服务端悄悄丢掉(用户只看到"按键没反应")。
    fn try_down(&mut self, idx: usize, others: usize) -> bool {
        if self.is_down(idx) || self.count >= MAX_CONCURRENT_KEYS {
            return false;
        }
        if self.count + others >= DEVICE_MAX_POINTERS {
            return false;
        }
        // 防御:调用方本应先 align,但引擎线程一旦 panic 就等于整个映射失效,
        // 所以这里宁可自己补一格,也不让越界索引把线程带走。
        if idx >= self.down.len() {
            self.down.resize(idx + 1, false);
        }
        self.down[idx] = true;
        self.count += 1;
        true
    }

    /// 登记一次抬起;仅当确有按下记录时返回 true(调用方据此注入 UP)
    fn release(&mut self, idx: usize) -> bool {
        if self.is_down(idx) {
            self.down[idx] = false;
            self.count = self.count.saturating_sub(1);
            return true;
        }
        false
    }

    fn free_all(&mut self) {
        for v in &mut self.down {
            *v = false;
        }
        self.count = 0;
    }
}

/// 物理按键状态镜像:当前**物理上真的按住**的键码集合。
///
/// 为什么必须有它:临时轮盘启用/停用时,同一个物理键的归属会在"轮盘方向"与
/// "普通绑定"之间来回切换,而键盘事件是边沿触发的 —— 切换的那一瞬间,
/// 引擎必须知道这个键此刻到底还按着没有。否则停用摇杆后,那个键的普通绑定要等
/// 用户"松开再按一次"才重新生效(用户反馈:"松开启用键后,那个键必须松开手一次
/// 才能触发。战场是瞬息万变的,所以请修复他")。
///
/// 它只认按键事件,不受配置改动、轮盘启用状态影响,因此是唯一可信的依据。
#[derive(Default)]
struct Held {
    codes: HashSet<u16>,
}

impl Held {
    fn set(&mut self, code: u16, pressed: bool) {
        if pressed {
            self.codes.insert(code);
        } else {
            self.codes.remove(&code);
        }
    }

    fn has(&self, code: u16) -> bool {
        self.codes.contains(&code)
    }
}

/// 引擎运行状态快照(界面诊断显示,回答"为什么按了没反应")
#[derive(Default, Clone, Copy)]
pub struct EngineLive {
    /// 当前占用的注入触点数(设备端最多同时 [`DEVICE_MAX_POINTERS`] 个)
    pub pointers: usize,
    /// 因触点池已满而被放弃的按下次数(累计)
    pub refused: u64,
    /// 最近一次被放弃的按键(便于定位是哪个键被挤掉)
    pub last_refused: u16,
}

/// 把"普通绑定"的实际按下状态对齐到物理按键状态。
///
/// 这是"归属切换"这条铁律的落地点:凡是会让某个物理键改换门庭的操作
/// (临时轮盘启用/停用、总开关切换、配置被编辑),都要在之后调用它。
///
/// 只对**状态型**动作对账:
///   * `Hold`      —— 按着就该有触点,松开就该抬起;
///   * `AndroidKey`—— 同上(系统键也要成对);
///   * `Tap`(duration=0)是"按一下翻一次"的开关、`Tap`(duration>0)与 `Swipe`
///     是一次性动作,都由事件自己收尾 —— 在这里对账会把它们反复翻转/重放。
///
/// 归属给某个生效中的轮盘方向键、或临时轮盘启用键的物理键不参与普通绑定
/// (与事件路径的优先级链完全一致:总开关键 > 启用键 > 轮盘方向键 > 普通绑定)。
fn reconcile_binds(
    ctl: &ControlClient,
    m: &Mapper,
    profile: &Profile,
    wheels: &[WheelState],
    fps_running: bool,
    aim_pointers: usize,
    held: &Held,
    fingers: &mut Fingers,
    active_android_keys: &mut HashSet<u16>,
    live: &mut EngineLive,
) {
    // 轮盘与瞄准占用的触点(普通绑定自己不占;对账期间它们不变)
    let reserved = wheel_pointers(wheels) + aim_pointers;
    for (idx, bind) in profile.binds.iter().enumerate() {
        if bind.fps_only {
            continue;
        }
        let want = held.has(bind.key)
            && !key_owned_by_wheel(profile, wheels, bind.key)
            && !key_owned_by_fps(profile, fps_running, bind.key);
        match &bind.action {
            Action::Hold { x, y, .. } => {
                let pid = bind_pid(idx);
                let (px, py) = m.point(*x, *y);
                if want {
                    if !fingers.is_down(idx) {
                        if fingers.try_down(idx, reserved) {
                            ctl.touch_down(pid, px, py);
                        } else {
                            refuse(live, bind.key);
                        }
                    }
                } else if fingers.release(idx) {
                    ctl.touch_up(pid, px, py);
                }
            }
            Action::AndroidKey { keycode } => {
                let kc = *keycode as u16;
                if want {
                    if active_android_keys.insert(kc) {
                        ctl.key(true, *keycode);
                    }
                } else if active_android_keys.remove(&kc) {
                    ctl.key(false, *keycode);
                }
            }
            _ => {}
        }
    }
}

/// 把轮盘方向状态对齐到物理按键状态(与 [`reconcile_binds`] 同理)。
///
/// 方向状态完全由"该轮盘此刻是否生效 × 对应物理键是否按着"决定,于是:
///   * 启用临时摇杆的瞬间,已按着的方向键立刻推动摇杆(而不是要重按一次);
///   * 停用/配置变化/切总开关时,不再生效的方向一定被抬起来;
///   * 不会出现"某个方向永远以为自己被按着"。
///
/// `extra_pointers` 是普通绑定 + 瞄准此刻占用的触点数(它们与轮盘抢同一个池子)。
fn reconcile_wheels(
    ctl: &ControlClient,
    m: &Mapper,
    profile: &Profile,
    wheels: &mut [WheelState],
    held: &Held,
    extra_pointers: usize,
    live: &mut EngineLive,
) {
    for (j, w) in profile.wheels.iter().enumerate() {
        if j >= wheels.len() {
            break;
        }
        let engaged = w.temp.is_none() || wheels[j].active;
        if w.kind == WheelKind::Standard {
            for (d, key) in [w.up, w.down, w.left, w.right].iter().enumerate() {
                let want = engaged && held.has(*key);
                if want && !wheels[j].pressed[d] {
                    wheels[j].next_seq = wheels[j].next_seq.wrapping_add(1);
                    wheels[j].press_seq[d] = wheels[j].next_seq;
                }
                wheels[j].pressed[d] = want;
            }
        } else {
            for (d, (_, key)) in w.active_dirs().iter().take(8).enumerate() {
                let want = engaged && held.has(*key);
                if want && !wheels[j].custom_pressed[d] {
                    wheels[j].next_seq = wheels[j].next_seq.wrapping_add(1);
                    wheels[j].custom_seq[d] = wheels[j].next_seq;
                }
                wheels[j].custom_pressed[d] = want;
            }
        }
        // 本轮盘此刻若已经按着,update_wheel 不会再去申请新触点,故不必减掉自己
        let reserved = extra_pointers + wheel_pointers(wheels);
        if update_wheel(ctl, m, j, w, &mut wheels[j], reserved) {
            refuse(live, w.up);
        }
    }
}

/// 该物理键此刻是否归摇杆(生效中的轮盘方向键,或任意临时轮盘的启用键)。
///
/// 临时轮盘的启用键**无论是否生效**都归它自己:事件路径上它总是被消费掉
/// (见 run() 里的启用键分支),所以普通绑定永远收不到它。
fn key_owned_by_wheel(profile: &Profile, wheels: &[WheelState], code: u16) -> bool {
    profile.wheels.iter().enumerate().any(|(j, w)| {
        if let Some(t) = &w.temp {
            if t.key == code {
                return true;
            }
        }
        let engaged = w.temp.is_none() || wheels.get(j).map(|s| s.active).unwrap_or(false);
        engaged && w.owns_key(code)
    })
}

/// 轮盘此刻占用的触点数(每个轮盘最多一个:按着才有)
/// 该物理键此刻是否被生效中的 FPS 专用键位占用。
/// 只要 FPS 模式正在运行,同键的 fps_only 映射就覆盖普通映射。
fn key_owned_by_fps(profile: &Profile, fps_running: bool, code: u16) -> bool {
    fps_running && profile.binds.iter().any(|b| b.fps_only && b.key == code)
}

fn wheel_pointers(wheels: &[WheelState]) -> usize {
    wheels.iter().filter(|w| w.down).count()
}

/// 记一次"因为触点池满而放弃按下"。
///
/// 除了计数,还要往诊断日志里留一行**带现场数字**的记录:仅凭"被放弃 3 次"
/// 无法判断是"用户真按了那么多键"还是"某处状态虚高把预算吃光了"。
fn refuse(live: &mut EngineLive, code: u16) {
    live.refused += 1;
    if code != 0 {
        live.last_refused = code;
    }
    crate::diag_warn!(
        "engine",
        "触点池已满,放弃这次按下: {} (当时占用 {}/{},普通键位并发上限 {})",
        if code == 0 {
            "瞄准".to_string()
        } else {
            key_name(code)
        },
        live.pointers,
        DEVICE_MAX_POINTERS,
        MAX_CONCURRENT_KEYS
    );
}

/// 往界面日志里留一句话(引擎线程没有日志所有权,只能放进 [`Shared::notices`])。
///
/// 参数取 `&mut Vec<String>` 而不是 `&mut Shared`:调用点上常常同时借着
/// `shared.control`/`shared.profile`,整结构可变借用会打架,而"借一个字段"
/// 借用检查器是允许的。
fn notify(notices: &mut Vec<String>, msg: impl Into<String>) {
    // 上限很小:这只是"给你一句解释",不是日志系统(真正的日志在界面侧)
    if notices.len() < 16 {
        notices.push(msg.into());
    }
}

/// 物理按键的"上升沿":这一次事件是不是这个键**刚被按下**(而不是自动重复)。
///
/// 为什么必须区分:Windows 的按键自动重复会以 KeyPress 反复上报(低级钩子不区分),
/// 长按 F8 半秒就能来十几次 —— 如果每次事件都翻转映射开关,
/// 用户看到的就是"按了 F8 却没反应 / 状态跟自己以为的不一样,
/// 必须再关一次开一次才恢复",而且没有任何日志可查。
/// 需要"按一下翻一次"的地方(总开关键、切换模式的启用键)统统只认上升沿。
fn rising_edge(pressed: bool, was_down: bool) -> bool {
    pressed && !was_down
}

/// 抬起当前所有普通绑定触点与系统键(状态重建/结构变化前调用)。
/// 不动轮盘与瞄准 —— 它们各有自己的释放路径。
///
/// 遍历的是**按下表本身的长度**而不是当前配置的绑定数:用户删掉几个键位时,
/// 那几个被删掉的槽位里可能还记着"按着",漏掉它们就是永久卡在设备上的触点。
/// 越界槽位用 (0,0) 抬起 —— 坐标一定落在屏内,不会因为"落在屏外"被系统整条丢弃。
fn release_all_binds(
    ctl: &ControlClient,
    m: &Mapper,
    profile: &Profile,
    fingers: &mut Fingers,
    active_android_keys: &mut HashSet<u16>,
) {
    let n = fingers.down.len().max(profile.binds.len());
    for idx in 0..n {
        if fingers.release(idx) {
            let (x, y) = bind_point(profile, m, idx);
            ctl.touch_up(bind_pid(idx), x, y);
        }
    }
    for kc in active_android_keys.drain() {
        ctl.key(false, kc as u32);
    }
    fingers.free_all();
}

/// 让引擎的运行状态与当前配置对齐;返回是否发生了结构变化。
///
/// 用户随时可能在开打中增删键位/摇杆,索引会整体位移。这里的原则是
/// **宁可抬手重算,绝不带着旧状态跑**:
///   * 普通绑定表结构变了 -> 先抬起全部绑定触点与系统键,再重建按下表;
///   * 轮盘表结构变了 -> 先用旧状态把在按的轮盘触点抬起来(回中再抬),
///     再按新配置重建轮盘状态。
/// 重建后**按物理按键状态恢复临时轮盘的启用标记**(长按模式):用户正按着某个
/// 启用键时,重建不该让摇杆"悄悄失效"。调用方在返回 true 时应立刻对账一次,
/// 把仍按着的键/方向补回来 —— 于是对玩家来说,增删一个键位或摇杆是无感的。
fn sync_structures(
    ctl: &ControlClient,
    m: &Mapper,
    profile: &Profile,
    wheels: &mut Vec<WheelState>,
    wheel_sig: &mut u64,
    binds_sig: &mut u64,
    fingers: &mut Fingers,
    active_android_keys: &mut HashSet<u16>,
    held: &Held,
) -> bool {
    let mut changed = false;

    // ---- 普通绑定 ----
    let bs = binds_signature(&profile.binds);
    if bs != *binds_sig {
        *binds_sig = bs;
        release_all_binds(ctl, m, profile, fingers, active_android_keys);
        // 按下表按新长度重建(旧槽位里的残留已被 free_all 清掉)
        fingers.down.clear();
        fingers.align(profile.binds.len());
        changed = true;
    }
    fingers.align(profile.binds.len());

    // ---- 轮盘 ----
    let ws = wheel_signature(&profile.wheels);
    if ws != *wheel_sig {
        *wheel_sig = ws;
        for (j, st) in wheels.iter_mut().enumerate() {
            if !st.down {
                continue;
            }
            // 回中再抬:旧圆心若在新配置里已经不在了,就用最后推送的位置,
            // 兜底也要给一个屏内坐标 —— 落在屏外的 UP 会被系统整条丢弃,
            // 那个触点就永远留在设备上了。
            let (cx, cy) = profile
                .wheels
                .get(j)
                .map(|w| m.point(w.cx, w.cy))
                .unwrap_or(st.last);
            ctl.touch_move(wheel_pid(j), cx, cy);
            ctl.touch_up(wheel_pid(j), cx, cy);
            st.down = false;
        }
        *wheels = vec![WheelState::default(); profile.wheels.len()];
        // 长按模式的临时轮盘:启用状态直接由"启用键是否还按着"恢复;
        // 切换模式是锁存状态,没有可信的物理依据,一律回到未启用(按一下即可再开)
        for (j, w) in profile.wheels.iter().enumerate() {
            if let Some(t) = &w.temp {
                wheels[j].active = t.mode == TempMode::Hold && held.has(t.key);
            }
        }
        changed = true;
    }
    changed
}

/// 普通绑定的结构指纹:数量 + 每个键的键码与动作类型。
///
/// 索引是引擎跟踪"哪个键按着"的依据(pid = 1000+idx)。用户增删一个键位,
/// 后面所有索引都会整体位移:旧触点的按下记录会被错记到别的键上,
/// 那个键于是"按了没反应",而真正的旧触点则永久留在设备上。
/// 因此指纹一变就必须先抬起全部触点、再按新配置重建。
fn binds_signature(binds: &[KeyBind]) -> u64 {
    let mut h = binds.len() as u64;
    for b in binds {
        let kind = match &b.action {
            Action::Tap { duration_ms, .. } => {
                if *duration_ms == 0 {
                    1
                } else {
                    2
                }
            }
            Action::Hold { .. } => 3,
            Action::Swipe(_) => 4,
            Action::AndroidKey { .. } => 5,
            Action::Macro(_) => 6,
        };
        h = h
            .wrapping_mul(0x100_0000_01b3)
            .wrapping_add(b.key as u64 + 1)
            .rotate_left(7)
            .wrapping_add(kind)
            .wrapping_add(if b.fps_only { 0x100 } else { 0 });
    }
    h
}

/// 轮盘的结构指纹:数量 + 方向键 + 启用键与模式。
///
/// 只关心会改变**键位归属与 pid 分配**的字段。坐标/半径/影响范围的变化不需要
/// 重建(下一帧推一下就是新的位置了),否则玩家一边调参一边打会被反复抬手。
///
/// 指纹变化必须"先释放旧触点、再重建状态",否则会同时踩中三种老毛病:
///   ① 旧触点永远留在设备上(触点池越用越少 → 新按键按不动);
///   ② 旧触点的 pid 被新轮盘接管(用户看到的"新摇杆与旧摇杆换位/乱动");
///   ③ 临时轮盘的启用状态错挂到别的轮盘上。
fn wheel_signature(wheels: &[Wheel]) -> u64 {
    let mut h = wheels.len() as u64;
    for w in wheels {
        for k in [w.up, w.down, w.left, w.right] {
            h = h.wrapping_mul(0x100_0000_01b3).wrapping_add(k as u64 + 1);
        }
        h = h.wrapping_mul(31).wrapping_add(match w.kind {
            WheelKind::Standard => 1,
            WheelKind::Custom => 2,
            WheelKind::Execute => 3,
        });
        for d in w.directions.iter().take(8) {
            h = h
                .wrapping_mul(31)
                .wrapping_add(d.key as u64 + 1)
                .wrapping_mul(31)
                .wrapping_add(d.angle_deg.to_bits() as u64);
        }
        h = h.wrapping_mul(31).wrapping_add(match w.mode {
            WheelMode::Classic => 1,
            WheelMode::Sensitive => 2,
        });
        match &w.temp {
            None => h = h.wrapping_mul(31).wrapping_add(0x9E37_79B9),
            Some(t) => {
                h = h.wrapping_mul(31).wrapping_add(t.key as u64 + 1);
                h = h.wrapping_mul(31).wrapping_add(match t.mode {
                    TempMode::Hold => 1,
                    TempMode::Toggle => 2,
                });
            }
        }
    }
    h
}

// ============================ FPS 鼠标瞄准 ============================
// 手机 FPS 的视角靠"手指在屏幕上拖动"实现,而鼠标给的是相对位移,
// 因此这里维护一个独立的手指触点:
//   鼠标位移 -> 累积偏移 -> 落点 = 锚点 + 偏移 -> 注入 touch_move
// 偏移接近屏幕边界时无法继续转向,所以需要「抬指 + 在锚点重按」(=归中)。

/// 瞄准运行状态(供界面显示,用来确认"偏移到底有没有在累积、触点有没有落下")
#[derive(Default, Clone, Copy)]
pub struct AimLive {
    /// 收到的鼠标位移事件数
    pub motions: u64,
    /// 最近一次位移量
    pub last_dx: f32,
    pub last_dy: f32,
    /// 当前累积偏移
    pub ox: f32,
    pub oy: f32,
    /// 瞄准触点当前是否按在屏幕上
    pub down: bool,
    /// 当前是否满足瞄准生效条件
    pub active: bool,
    /// FPS 模式是否已由独立按键/界面开启
    pub mode_active: bool,
    /// 是否因按住临时退出键而暂停
    pub suspended: bool,
    /// 已注入的瞄准触点消息数(down/move/up 合计)
    pub sent: u64,
    /// 虚拟手柄是否已经在设备端创建
    pub gamepad_created: bool,
    /// 已发送的虚拟手柄输入报告数
    pub gamepad_reports: u64,
}

/// 瞄准子系统状态
#[derive(Default)]
struct AimState {
    /// 手指当前是否按在屏幕上
    down: bool,
    /// 累积偏移(设备像素,相对锚点)
    ox: f32,
    oy: f32,
    /// 当前落点(抬指时需要给出正确坐标)
    cur: (i32, i32),
    /// 门控键是否按住(hold_key == 0 时忽略)
    gate_down: bool,
    /// FPS 模式独立开关的锁存状态
    mode_active: bool,
    /// 按住临时退出键期间挂起,松开自动恢复
    suspended: bool,
    /// 用户按 Ctrl+Alt 临时把鼠标交还给系统:此时不瞄准、也不捕获光标
    released: bool,
    /// 最近一次鼠标位移时间(静止归中的依据)
    last_motion: Option<Instant>,
    /// 当前拖动使用的锚点;锚点被改动时重置拖动
    anchor_used: (i32, i32),
    /// 已注入的触点消息数(仅诊断用)
    sent: u64,
}

#[derive(Default)]
struct GamepadState {
    created: bool,
    right_x: f32,
    right_y: f32,
    last_motion: Option<Instant>,
    /// Segmented mode: hold the limit for a short time before sending center.
    pending_limit: Option<((f32, f32), Instant)>,
    /// Segmented mode: carry left after recentering, applied after a pause.
    pending_residual: Option<((f32, f32), Instant)>,
    /// Number of UHID input reports sent (diagnostics/UI).
    reports: u64,
}

/// 瞄准自身是否具备生效条件(是否映射开启由调用方判断)
fn fps_is_active(aim: &Aim, st: &AimState) -> bool {
    fps_mode_active(aim, st) && aim.anchor_set()
}

/// FPS/open-world camera mode is logically active.  This deliberately does
/// not require an anchor: pointer capture and cursor hiding must follow the
/// mode switch itself, while anchor-dependent touch aiming is checked by
/// [`fps_is_active`].
fn fps_mode_active(aim: &Aim, st: &AimState) -> bool {
    aim.enabled && st.mode_active && !st.suspended
}

fn aim_active(aim: &Aim, st: &AimState) -> bool {
    if aim.input_mode != ViewInputMode::TouchDrag {
        return false;
    }
    fps_is_active(aim, st) && !st.released && (aim.open_world || aim.hold_key == 0 || st.gate_down)
}

/// FPS 指针消隐条件:控制通道在线、FPS 正在运行、用户没有手动交还鼠标。
/// 与“是否正在瞄准”分离,因此绑了“按住才瞄准”时指针仍然会在 FPS 模式内消隐。
fn pointer_should_be_hidden(connected: bool, aim: &Aim, st: &AimState) -> bool {
    connected && aim.capture_mouse && fps_mode_active(aim, st) && !st.released
}

fn is_gamepad_mode(mode: ViewInputMode) -> bool {
    matches!(
        mode,
        ViewInputMode::VirtualGamepadContinuous | ViewInputMode::VirtualGamepadSegmented
    )
}

fn gamepad_active(aim: &Aim, st: &AimState) -> bool {
    is_gamepad_mode(aim.input_mode)
        && fps_mode_active(aim, st)
        && !st.released
        && (aim.open_world || aim.hold_key == 0 || st.gate_down)
}

fn gamepad_report(x: f32, y: f32) -> [u8; 15] {
    let x = x.round().clamp(0.0, GAMEPAD_AXIS_MAX) as u16;
    let y = y.round().clamp(0.0, GAMEPAD_AXIS_MAX) as u16;
    let center = GAMEPAD_AXIS_CENTER as u16;
    let mut report = [0u8; 15];
    report[0..2].copy_from_slice(&center.to_le_bytes());
    report[2..4].copy_from_slice(&center.to_le_bytes());
    report[4..6].copy_from_slice(&x.to_le_bytes());
    report[6..8].copy_from_slice(&y.to_le_bytes());
    report
}

fn send_gamepad_axes(ctl: &ControlClient, state: &mut GamepadState, x: f32, y: f32) {
    ctl.uhid_input(GAMEPAD_HID_ID, gamepad_report(x, y).to_vec());
    state.reports += 1;
}

fn send_gamepad_report(ctl: &ControlClient, state: &mut GamepadState) {
    let x = state.right_x;
    let y = state.right_y;
    send_gamepad_axes(ctl, state, x, y);
}

fn ensure_gamepad(ctl: &ControlClient, state: &mut GamepadState) {
    if state.created {
        return;
    }
    crate::diag_info!(
        "gamepad",
        "创建虚拟 Xbox 兼容手柄: id={} vendor=0x045E product=0x028E",
        GAMEPAD_HID_ID
    );
    ctl.uhid_create(
        GAMEPAD_HID_ID,
        0x045E,
        0x028E,
        "scrcpy-pad virtual gamepad",
        GAMEPAD_REPORT_DESC.to_vec(),
    );
    state.created = true;
    state.right_x = GAMEPAD_AXIS_CENTER;
    state.right_y = GAMEPAD_AXIS_CENTER;
    send_gamepad_report(ctl, state);
}

fn center_gamepad(ctl: &ControlClient, state: &mut GamepadState) {
    let changed = state.right_x != GAMEPAD_AXIS_CENTER
        || state.right_y != GAMEPAD_AXIS_CENTER
        || state.pending_limit.is_some()
        || state.pending_residual.is_some();
    state.right_x = GAMEPAD_AXIS_CENTER;
    state.right_y = GAMEPAD_AXIS_CENTER;
    state.last_motion = None;
    state.pending_limit = None;
    state.pending_residual = None;
    if state.created && changed {
        send_gamepad_report(ctl, state);
    }
}

fn flush_pending_gamepad(ctl: &ControlClient, state: &mut GamepadState) {
    if let Some(((x, y), _)) = state.pending_residual.take() {
        state.right_x = x;
        state.right_y = y;
        state.last_motion = Some(Instant::now());
        send_gamepad_report(ctl, state);
    }
}

/// Advance the segmented-mode phases. The limit report is held for
/// `GAMEPAD_LIMIT_HOLD`; only then is center sent, followed by the residual
/// after `GAMEPAD_RECENTER_PAUSE`.
fn advance_gamepad_phases(ctl: &ControlClient, state: &mut GamepadState) {
    let now = Instant::now();
    if state
        .pending_limit
        .as_ref()
        .is_some_and(|(_, deadline)| now >= *deadline)
    {
        let (carry, _) = state.pending_limit.take().unwrap();
        state.right_x = GAMEPAD_AXIS_CENTER;
        state.right_y = GAMEPAD_AXIS_CENTER;
        send_gamepad_report(ctl, state);
        state.pending_residual = Some((
            (
                (GAMEPAD_AXIS_CENTER + carry.0).clamp(0.0, GAMEPAD_AXIS_MAX),
                (GAMEPAD_AXIS_CENTER + carry.1).clamp(0.0, GAMEPAD_AXIS_MAX),
            ),
            Instant::now() + GAMEPAD_RECENTER_PAUSE,
        ));
    }
    if state
        .pending_residual
        .as_ref()
        .is_some_and(|(_, deadline)| now >= *deadline)
    {
        flush_pending_gamepad(ctl, state);
    }
}

fn destroy_gamepad(ctl: &ControlClient, state: &mut GamepadState) {
    if state.created {
        center_gamepad(ctl, state);
        ctl.uhid_destroy(GAMEPAD_HID_ID);
        state.created = false;
        crate::diag_info!("gamepad", "销毁虚拟手柄: id={}", GAMEPAD_HID_ID);
    }
}

fn gamepad_on_motion(
    ctl: &ControlClient,
    aim: &Aim,
    state: &mut GamepadState,
    aim_state: &AimState,
    dx: f32,
    dy: f32,
) -> bool {
    if !gamepad_active(aim, aim_state) {
        center_gamepad(ctl, state);
        return false;
    }

    advance_gamepad_phases(ctl, state);

    let add_x = dx * aim.sensitivity_x * aim.move_speed * GAMEPAD_AXIS_MOUSE_SCALE;
    let sy = if aim.invert_y {
        -aim.sensitivity_y
    } else {
        aim.sensitivity_y
    };
    let add_y = dy * sy * aim.move_speed * GAMEPAD_AXIS_MOUSE_SCALE;

    if let Some((carry, _)) = state.pending_limit.as_mut() {
        carry.0 = (carry.0 + add_x).clamp(-GAMEPAD_AXIS_MAX, GAMEPAD_AXIS_MAX);
        carry.1 = (carry.1 + add_y).clamp(-GAMEPAD_AXIS_MAX, GAMEPAD_AXIS_MAX);
        state.last_motion = Some(Instant::now());
        return false;
    }

    if state.pending_residual.is_some() {
        flush_pending_gamepad(ctl, state);
    }

    state.right_x += add_x;
    state.right_y += add_y;
    state.last_motion = Some(Instant::now());

    let segmented = aim.input_mode == ViewInputMode::VirtualGamepadSegmented;
    if !segmented {
        state.right_x = state.right_x.clamp(0.0, GAMEPAD_AXIS_MAX);
        state.right_y = state.right_y.clamp(0.0, GAMEPAD_AXIS_MAX);
        send_gamepad_report(ctl, state);
        return false;
    }

    let mut hit_x = false;
    let mut hit_y = false;
    let mut report_x = state.right_x;
    let mut report_y = state.right_y;
    if report_x > GAMEPAD_AXIS_MAX {
        report_x = GAMEPAD_AXIS_MAX;
        hit_x = true;
    } else if report_x < 0.0 {
        report_x = 0.0;
        hit_x = true;
    }
    if report_y > GAMEPAD_AXIS_MAX {
        report_y = GAMEPAD_AXIS_MAX;
        hit_y = true;
    } else if report_y < 0.0 {
        report_y = 0.0;
        hit_y = true;
    }

    if hit_x || hit_y {
        let carry_x = state.right_x - report_x;
        let carry_y = state.right_y - report_y;
        state.right_x = report_x;
        state.right_y = report_y;
        send_gamepad_axes(ctl, state, report_x, report_y);
        state.pending_limit = Some(((carry_x, carry_y), Instant::now() + GAMEPAD_LIMIT_HOLD));
    } else {
        send_gamepad_report(ctl, state);
    }
    false
}

fn gamepad_tick(
    ctl: &ControlClient,
    aim: &Aim,
    state: &mut GamepadState,
    aim_state: &AimState,
    enabled: bool,
) {
    advance_gamepad_phases(ctl, state);
    if !enabled || !gamepad_active(aim, aim_state) {
        center_gamepad(ctl, state);
        return;
    }
    if state.pending_limit.is_some() || state.pending_residual.is_some() {
        return;
    }
    let idle_ms = aim.recenter_idle_ms.max(16) as u128;
    let idle = state
        .last_motion
        .map(|time| time.elapsed().as_millis() >= idle_ms)
        .unwrap_or(false);
    if idle && (state.right_x != GAMEPAD_AXIS_CENTER || state.right_y != GAMEPAD_AXIS_CENTER) {
        center_gamepad(ctl, state);
    }
}

/// 在当前位置抬起瞄准触点并清空偏移
fn aim_lift(ctl: &ControlClient, st: &mut AimState) {
    if st.down {
        let (x, y) = st.cur;
        ctl.touch_up(AIM_PID, x, y);
        st.sent += 1;
        st.down = false;
    }
    st.ox = 0.0;
    st.oy = 0.0;
    st.last_motion = None;
}

/// 没有控制通道时只清理本地状态
fn aim_release_local(st: &mut AimState) {
    st.down = false;
    st.ox = 0.0;
    st.oy = 0.0;
    st.last_motion = None;
}

/// 锚点换算成像素并钳进当前屏幕内。锚点可能是在别的屏幕方向下取的
/// (例如竖屏取的锚点,横屏时 y 会超出屏幕高度),而落在屏幕外的触摸
/// 会被系统整条丢弃,表现为"鼠标怎么动都没有反应",因此注入前必须钳制。
fn aim_anchor(m: &Mapper, aim: &Aim) -> (i32, i32) {
    let (x, y) = m.point(aim.anchor_x, aim.anchor_y);
    (
        x.clamp(0, (m.w as i32 - 1).max(0)),
        y.clamp(0, (m.h as i32 - 1).max(0)),
    )
}

/// 应用拖动死区后的有效偏移。死区内的轻微手抖视为没有移动；
/// 越过死区后减去死区，避免刚离开死区时跳一下。
fn aim_effective_offset(aim: &Aim, st: &AimState) -> (f32, f32) {
    let dead = aim.drag_deadzone.clamp(0.0, 400.0);
    let mag = st.ox.hypot(st.oy);
    if mag <= dead || mag <= f32::EPSILON {
        return (0.0, 0.0);
    }
    let scale = (mag - dead) / mag;
    (st.ox * scale, st.oy * scale)
}

/// 落点 = 锚点 + 有效偏移。有边界时钳制到屏幕内，第三个返回值表示是否触边；
/// 关闭边界时保留完整偏移，由回转半径负责抬指/重按，避免屏幕边缘截断。
fn aim_target(m: &Mapper, aim: &Aim, st: &AimState) -> (i32, i32, bool) {
    let (ax, ay) = aim_anchor(m, aim);
    let axf = ax as f32;
    let ayf = ay as f32;
    let (ox, oy) = aim_effective_offset(aim, st);
    if !aim.boundary {
        return ((axf + ox).round() as i32, (ayf + oy).round() as i32, false);
    }
    let max_ox = (m.w - 1.0 - axf).max(0.0);
    let max_oy = (m.h - 1.0 - ayf).max(0.0);
    let cx = ox.clamp(-axf.max(0.0), max_ox);
    let cy = oy.clamp(-ayf.max(0.0), max_oy);
    let hit_edge = cx != ox || cy != oy;
    (
        (axf + cx).round() as i32,
        (ayf + cy).round() as i32,
        hit_edge,
    )
}

/// 归中:在当前位置抬指,回到锚点重新按下。
/// 这一轮拖动产生的转向已经生效,玩家侧只是看到视角继续转动。
fn aim_recenter(ctl: &ControlClient, m: &Mapper, aim: &Aim, st: &mut AimState) {
    if !st.down {
        st.ox = 0.0;
        st.oy = 0.0;
        return;
    }
    let (cx, cy) = st.cur;
    ctl.touch_up(AIM_PID, cx, cy);
    st.sent += 1;
    st.ox = 0.0;
    st.oy = 0.0;
    let (ax, ay) = aim_anchor(m, aim);
    ctl.touch_down(AIM_PID, ax, ay);
    st.sent += 1;
    st.cur = (ax, ay);
    // 刚归中,重置静止计时,避免立刻再次归中
    st.last_motion = Some(Instant::now());
}

/// 无边界模式的回转：抬指、保留超出回转半径的余量、在锚点重按，
/// 让持续同向移动不会因为触点超出屏幕而被系统丢弃或被边界截断。
fn aim_recenter_with_carry(
    ctl: &ControlClient,
    m: &Mapper,
    aim: &Aim,
    st: &mut AimState,
    radius: f32,
) {
    if !st.down {
        st.ox = 0.0;
        st.oy = 0.0;
        return;
    }
    let (cx, cy) = st.cur;
    ctl.touch_up(AIM_PID, cx, cy);
    st.sent += 1;
    let mag = st.ox.hypot(st.oy);
    if mag > radius && mag > f32::EPSILON {
        let keep = (mag - radius) / mag;
        st.ox *= keep;
        st.oy *= keep;
    } else {
        st.ox = 0.0;
        st.oy = 0.0;
    }
    let (ax, ay) = aim_anchor(m, aim);
    ctl.touch_down(AIM_PID, ax, ay);
    st.sent += 1;
    st.cur = (ax, ay);
    let (tx, ty, _) = aim_target(m, aim, st);
    ctl.touch_move(AIM_PID, tx, ty);
    st.cur = (tx, ty);
    st.last_motion = Some(Instant::now());
}
/// 鼠标相对位移 -> 手机上的拖动。
/// 返回是否因为触点池已满而没能落下瞄准触点(供诊断计数;落不下就不落下,
/// 下一次位移会再试,不会留下半个状态)。
fn aim_on_motion(
    ctl: &ControlClient,
    m: &Mapper,
    aim: &Aim,
    st: &mut AimState,
    dx: f32,
    dy: f32,
    reserved: usize,
) -> bool {
    if aim.open_world {
        return open_world_on_motion(ctl, m, aim, st, dx, dy, reserved);
    }
    if !aim_active(aim, st) {
        return false;
    }
    if !st.down && reserved >= DEVICE_MAX_POINTERS {
        return true;
    }
    let anchor = aim_anchor(m, aim);
    // 锚点被改动过(或屏幕方向变了):结束旧拖动,从新锚点重新开始
    if st.anchor_used != anchor {
        aim_lift(ctl, st);
        st.anchor_used = anchor;
    }

    st.ox += dx * aim.sensitivity_x * aim.move_speed;
    let sy = if aim.invert_y {
        -aim.sensitivity_y
    } else {
        aim.sensitivity_y
    };
    st.oy += dy * sy * aim.move_speed;
    let dead = aim.drag_deadzone.clamp(0.0, 400.0);
    let mag = st.ox.hypot(st.oy);
    if mag <= dead {
        // 死区内只累计偏移，不注入移动；last_motion 不刷新，
        // 因此静止归中计时会继续走，稍后自动抬指回锚点。
        return false;
    }
    st.last_motion = Some(Instant::now());

    let (tx, ty, hit_edge) = aim_target(m, aim, st);
    if st.down {
        ctl.touch_move(AIM_PID, tx, ty);
    } else {
        ctl.touch_down(AIM_PID, tx, ty);
        st.down = true;
    }
    st.sent += 1;
    st.cur = (tx, ty);

    let th = aim.recenter_threshold.max(8) as f32;
    if !aim.boundary {
        // 无边界：把“回转半径”当作换手阈值，抬指后保留超出量继续同向转动。
        // 即使归中策略是 Never 也保留这条安全机制，否则坐标会无限累积。
        if mag > th {
            aim_recenter_with_carry(ctl, m, aim, st, th);
        }
    } else if aim.recenter == RecenterMode::Threshold && (st.ox.abs() >= th || st.oy.abs() >= th) {
        // 有边界：触边后不自动回转，保持“滑到边就不动”的手感；
        // 只有用户明确选择“阈值归中”时才在阈值处回转。
        aim_recenter(ctl, m, aim, st);
    } else {
        let _ = hit_edge;
    }
    false
}

/// Open-world camera mode: relative mouse movement is mapped to a touch
/// "treadmill".  Horizontal motion is kept inside a comfortable sweep band;
/// when the cursor would cross the band, the finger is lifted and re-pressed
/// at the anchor while carrying the excess movement forward.  This avoids the
/// edge-stops of a plain drag and keeps continuous left/right turning smooth.
fn open_world_on_motion(
    ctl: &ControlClient,
    m: &Mapper,
    aim: &Aim,
    st: &mut AimState,
    dx: f32,
    dy: f32,
    reserved: usize,
) -> bool {
    if !aim_active(aim, st) {
        return false;
    }
    if !st.down && reserved >= DEVICE_MAX_POINTERS {
        return true;
    }

    let anchor = aim_anchor(m, aim);
    if st.anchor_used != anchor {
        aim_lift(ctl, st);
        st.anchor_used = anchor;
    }

    let alpha = aim.open_world_smoothing.clamp(0.15, 1.0);
    st.ox += dx * aim.sensitivity_x * alpha * aim.move_speed;
    let sy = if aim.invert_y {
        -aim.sensitivity_y
    } else {
        aim.sensitivity_y
    };
    st.oy += dy * sy * alpha * aim.move_speed;
    let dead = aim.drag_deadzone.clamp(0.0, 400.0);
    if st.ox.hypot(st.oy) <= dead {
        return false;
    }
    st.last_motion = Some(Instant::now());

    let left_room = anchor.0 as f32;
    let right_room = (m.w - 1.0 - anchor.0 as f32).max(0.0);
    let safe_radius = left_room.min(right_room).max(16.0);
    let radius = (m.w * aim.open_world_radius.clamp(0.05, 0.45))
        .min(safe_radius)
        .max(8.0);
    let mut carried = 0.0;
    if st.ox > radius {
        carried = st.ox - radius;
        st.ox = radius;
    } else if st.ox < -radius {
        carried = st.ox + radius;
        st.ox = -radius;
    }

    let (tx, ty, _) = aim_target(m, aim, st);
    if !st.down {
        ctl.touch_down(AIM_PID, anchor.0, anchor.1);
        st.down = true;
        st.cur = anchor;
    }
    ctl.touch_move(AIM_PID, tx, ty);
    st.cur = (tx, ty);

    if carried != 0.0 {
        // Seamless recenter: lift, reset to the anchor, then immediately apply
        // the residual offset so the camera keeps moving in the same direction.
        ctl.touch_up(AIM_PID, tx, ty);
        st.ox = carried.clamp(-radius, radius);
        st.oy = 0.0;
        let (rx, ry, _) = aim_target(m, aim, st);
        ctl.touch_down(AIM_PID, anchor.0, anchor.1);
        ctl.touch_move(AIM_PID, rx, ry);
        st.cur = (rx, ry);
    }
    false
}

/// 定期维护:映射关闭/门控松开 -> 收手;静止归中 -> 回锚点
fn aim_tick(ctl: &ControlClient, m: &Mapper, aim: &Aim, st: &mut AimState) {
    if !aim_active(aim, st) {
        aim_lift(ctl, st);
        return;
    }
    if !st.down || aim.recenter != RecenterMode::Idle {
        return;
    }
    let idle_ms = aim.recenter_idle_ms.max(16) as u128;
    let paused = st
        .last_motion
        .map(|t| t.elapsed().as_millis() >= idle_ms)
        .unwrap_or(false);
    if paused && (st.ox != 0.0 || st.oy != 0.0) {
        aim_recenter(ctl, m, aim, st);
    }
}

